"""IDTReeS dataset (ported from torchgeo.datasets.idtrees)."""

import glob
import os

import geopandas as gpd
import numpy as np
import pandas as pd
import rasterio
from keras import ops
from rasterio.enums import Resampling

from .errors import DatasetNotFoundError
from .geo import NonGeoDataset
from .utils import download_url, extract_archive, lazy_import, quantile_normalization


class IDTReeS(NonGeoDataset):
    """IDTReeS dataset.

    The `IDTReeS <https://idtrees.org/competition/>`__ dataset is a dataset
    for tree crown detection.

    Dataset features:

    * RGB Image, Canopy Height Model (CHM), Hyperspectral Image (HSI), LiDAR
      Point Cloud
    * Remote sensing and field data generated by the National Ecological
      Observatory Network (NEON)
    * 0.1 - 1m resolution imagery
    * Task 1 - object detection (tree crown delination)
    * Task 2 - object classification (species classification)
    * Train set contains 85 images
    * Test set (task 1) contains 153 images
    * Test set (task 2) contains 353 images and tree crown polygons

    Dataset format:

    * optical - three-channel RGB 200x200 geotiff
    * canopy height model - one-channel 20x20 geotiff
    * hyperspectral - 369-channel 20x20 geotiff
    * point cloud - Nx3 LAS file (.las), some files contain RGB colors per point
    * shapefiles (.shp) containing polygons
    * csv file containing species labels and other metadata for each polygon

    If you use this dataset in your research, please cite the following
    paper:

    * https://doi.org/10.1101/2021.08.06.453503

    This dataset requires the following additional library to be installed:

    * `laspy <https://pypi.org/project/laspy/>`_ to read lidar point clouds
    """

    classes = {
        "ACPE": "Acer pensylvanicum L.",
        "ACRU": "Acer rubrum L.",
        "ACSA3": "Acer saccharum Marshall",
        "AMLA": "Amelanchier laevis Wiegand",
        "BETUL": "Betula sp.",
        "CAGL8": "Carya glabra (Mill.) Sweet",
        "CATO6": "Carya tomentosa (Lam.) Nutt.",
        "FAGR": "Fagus grandifolia Ehrh.",
        "GOLA": "Gordonia lasianthus (L.) Ellis",
        "LITU": "Liriodendron tulipifera L.",
        "LYLU3": "Lyonia lucida (Lam.) K. Koch",
        "MAGNO": "Magnolia sp.",
        "NYBI": "Nyssa biflora Walter",
        "NYSY": "Nyssa sylvatica Marshall",
        "OXYDE": "Oxydendrum sp.",
        "PEPA37": "Persea palustris (Raf.) Sarg.",
        "PIEL": "Pinus elliottii Engelm.",
        "PIPA2": "Pinus palustris Mill.",
        "PINUS": "Pinus sp.",
        "PITA": "Pinus taeda L.",
        "PRSE2": "Prunus serotina Ehrh.",
        "QUAL": "Quercus alba L.",
        "QUCO2": "Quercus coccinea",
        "QUGE2": "Quercus geminata Small",
        "QUHE2": "Quercus hemisphaerica W. Bartram ex Willd.",
        "QULA2": "Quercus laevis Walter",
        "QULA3": "Quercus laurifolia Michx.",
        "QUMO4": "Quercus montana Willd.",
        "QUNI": "Quercus nigra L.",
        "QURU": "Quercus rubra L.",
        "QUERC": "Quercus sp.",
        "ROPS": "Robinia pseudoacacia L.",
        "TSCA": "Tsuga canadensis (L.) Carriere",
    }
    metadata = {
        "train": {
            "url": "https://zenodo.org/records/3934932/files/IDTREES_competition_train_v2.zip?download=1",
            "md5": "5ddfa76240b4bb6b4a7861d1d31c299c",
            "filename": "IDTREES_competition_train_v2.zip",
        },
        "test": {
            "url": "https://zenodo.org/records/3934932/files/IDTREES_competition_test_v2.zip?download=1",
            "md5": "b108931c84a70f2a38a8234290131c9b",
            "filename": "IDTREES_competition_test_v2.zip",
        },
    }
    directories = {"train": ["train"], "test": ["task1", "task2"]}
    image_size = (200, 200)

    def __init__(
        self,
        root="data",
        split="train",
        task="task1",
        transforms=None,
        download=False,
        checksum=True,
    ):
        """Initialize a new IDTReeS dataset instance.

        Args:
            root: root directory where dataset can be found
            split: one of "train" or "test"
            task: 'task1' for detection, 'task2' for detection + classification
                (only relevant for split='test')
            transforms: a function/transform that takes input sample and its
                target as entry and returns a transformed version
            download: if True, download dataset and store it in the root directory
            checksum: if True, check the MD5 of the downloaded files

        Raises:
            DatasetNotFoundError: If dataset is not found and *download* is False.
            DependencyNotFoundError: If laspy is not installed.
        """
        lazy_import("laspy")

        assert split in ["train", "test"]
        assert task in ["task1", "task2"]

        self.root = root
        self.split = split
        self.task = task
        self.transforms = transforms
        self.download = download
        self.checksum = checksum
        self.class2idx = {c: i for i, c in enumerate(self.classes)}
        self.idx2class = {i: c for i, c in enumerate(self.classes)}
        self.num_classes = len(self.classes)
        self._verify()
        self.images, self.geometries, self.labels = self._load(root)

    def __getitem__(self, index):
        """Return an index within the dataset."""
        path = self.images[index]
        image = ops.cast(self._load_image(path), "uint8")
        hsi = self._load_image(path.replace("RGB", "HSI"))
        chm = self._load_image(path.replace("RGB", "CHM"))
        las = self._load_las(path.replace("RGB", "LAS").replace(".tif", ".las"))
        sample = {"image": image, "hsi": hsi, "chm": chm, "las": las}

        if self.split == "test":
            if self.task == "task2":
                sample["bbox_xyxy"] = self._load_boxes(path)
                h, w = sample["image"].shape[:2]
                sample["bbox_xyxy"], _ = self._filter_boxes(
                    image_size=(h, w),
                    min_size=1,
                    boxes=sample["bbox_xyxy"],
                    labels=None,
                )
        else:
            sample["bbox_xyxy"] = self._load_boxes(path)
            sample["label"] = self._load_target(path)

            h, w = sample["image"].shape[:2]
            sample["bbox_xyxy"], sample["label"] = self._filter_boxes(
                image_size=(h, w),
                min_size=1,
                boxes=sample["bbox_xyxy"],
                labels=sample["label"],
            )

        if self.transforms is not None:
            sample = self.transforms(sample)

        return sample

    def __len__(self):
        """Return the number of data points in the dataset."""
        return len(self.images)

    def _load_image(self, path):
        """Load a tiff file."""
        with rasterio.open(path) as f:
            array = f.read(out_shape=self.image_size, resampling=Resampling.bilinear)
        array = np.transpose(array, (1, 2, 0))
        tensor = ops.convert_to_tensor(array.astype("float32"))
        return tensor

    def _load_las(self, path):
        """Load a single point cloud.

        Returns a ``[3, N]`` tensor of xyz point coordinates. Unlike image
        samples, a point cloud has no spatial H/W/C axes, so it is left
        untouched by the channels-last convention used elsewhere.
        """
        laspy = lazy_import("laspy")
        las = laspy.read(path)
        array = np.stack([las.x, las.y, las.z], axis=0)
        tensor = ops.convert_to_tensor(array)
        return tensor

    def _load_boxes(self, path):
        """Load object bounding boxes."""
        base_path = os.path.basename(path)
        geometries = self.geometries

        # Find object ids and geometries
        # The train set geometry->image mapping is contained
        # in the train/Field/itc_rsFile.csv file
        if self.split == "train":
            indices = self.labels["rsFile"] == base_path
            ids = self.labels[indices]["id"].tolist()
            geoms = [geometries[i]["geometry"] for i in ids]
        # The test set has no mapping csv. The mapping is inside of the geometry
        # properties i.e. geom["property"]["plotID"] contains the RGB image filename
        # Return all geometries with the matching RGB image filename of the sample
        else:
            ids = [
                k
                for k, v in geometries.items()
                if v["properties"]["plotID"] == base_path
            ]
            geoms = [geometries[i]["geometry"] for i in ids]

        # Convert to pixel coords
        boxes = []
        with rasterio.open(path) as f:
            for geom in geoms:
                xmin, ymin, xmax, ymax = geom.bounds
                row_min, col_min = f.index(xmin, ymin)
                row_max, col_max = f.index(xmax, ymax)
                xmin_px = min(col_min, col_max)
                xmax_px = max(col_min, col_max)
                ymin_px = min(row_min, row_max)
                ymax_px = max(row_min, row_max)
                boxes.append([xmin_px, ymin_px, xmax_px, ymax_px])

        tensor = ops.convert_to_tensor(np.array(boxes, dtype="float32"))
        return tensor

    def _load_target(self, path):
        """Load target label for a single sample."""
        # Find indices for objects in the image
        base_path = os.path.basename(path)
        indices = self.labels["rsFile"] == base_path

        # Load object labels
        classes = self.labels[indices]["taxonID"].tolist()
        labels = [self.class2idx[c] for c in classes]
        tensor = ops.convert_to_tensor(np.array(labels, dtype="int64"))
        return tensor

    def _load(self, root):
        """Load files, geometries, and labels."""
        if self.split == "train":
            directory = os.path.join(root, self.directories[self.split][0])
            labels = self._load_labels(directory)
            geoms = self._load_geometries(directory)
        else:
            directory = os.path.join(root, self.task)
            if self.task == "task1":
                geoms = None
                labels = None
            else:
                geoms = self._load_geometries(directory)
                labels = None

        images = glob.glob(os.path.join(directory, "RemoteSensing", "RGB", "*.tif"))

        return images, geoms, labels

    def _load_labels(self, directory):
        """Load the csv files containing the labels."""
        path_mapping = os.path.join(directory, "Field", "itc_rsFile.csv")
        path_labels = os.path.join(directory, "Field", "train_data.csv")
        df_mapping = pd.read_csv(path_mapping)
        df_labels = pd.read_csv(path_labels)
        df_mapping = df_mapping.set_index("indvdID", drop=True)
        df_labels = df_labels.set_index("indvdID", drop=True)
        df = df_labels.join(df_mapping, on="indvdID")
        df = df.drop_duplicates()
        df.reset_index()
        return df

    def _load_geometries(self, directory):
        """Load the shape files containing the geometries."""
        filepaths = glob.glob(os.path.join(directory, "ITC", "*.shp"))

        i = 0
        features = {}
        for path in filepaths:
            gdf = gpd.read_file(path)
            for _, row in gdf.iterrows():
                # The train set has a unique id for each geometry in the properties
                if self.split == "train":
                    features[row["id"]] = {
                        "geometry": row.geometry,
                        "properties": row.drop("geometry").to_dict(),
                    }
                # The test set has no unique id so create a dummy id
                else:
                    features[i] = {
                        "geometry": row.geometry,
                        "properties": row.drop("geometry").to_dict(),
                    }
                    i += 1
        return features

    def _filter_boxes(self, image_size, min_size, boxes, labels):
        """Clip boxes to image size and filter boxes with sides less than ``min_size``.

        A dependency-free equivalent of
        ``torchvision.ops.clip_boxes_to_image``/``remove_small_boxes``.

        Args:
            image_size: tuple of (height, width) of image
            min_size: filter boxes that have any side less than min_size
            boxes: [N, 4] shape tensor of xyxy bounding box coordinates
            labels: (Optional) [N,] shape tensor of bounding box labels

        Returns:
            a tuple of filtered boxes and labels
        """
        h, w = image_size
        boxes_np = ops.convert_to_numpy(boxes).astype("float32")

        if boxes_np.size == 0:
            filtered_boxes = ops.convert_to_tensor(boxes_np.reshape(0, 4))
            return filtered_boxes, labels

        boxes_np[:, 0] = np.clip(boxes_np[:, 0], 0, w)
        boxes_np[:, 2] = np.clip(boxes_np[:, 2], 0, w)
        boxes_np[:, 1] = np.clip(boxes_np[:, 1], 0, h)
        boxes_np[:, 3] = np.clip(boxes_np[:, 3], 0, h)

        widths = boxes_np[:, 2] - boxes_np[:, 0]
        heights = boxes_np[:, 3] - boxes_np[:, 1]
        keep = (widths >= min_size) & (heights >= min_size)

        filtered_boxes = ops.convert_to_tensor(boxes_np[keep])

        filtered_labels = None
        if labels is not None:
            labels_np = ops.convert_to_numpy(labels)[keep]
            filtered_labels = ops.convert_to_tensor(labels_np)

        return filtered_boxes, filtered_labels

    def _verify(self):
        """Verify the integrity of the dataset."""
        url = self.metadata[self.split]["url"]
        md5 = self.metadata[self.split]["md5"]
        filename = self.metadata[self.split]["filename"]
        directories = self.directories[self.split]

        # Check if the files already exist
        exists = [
            os.path.exists(os.path.join(self.root, directory))
            for directory in directories
        ]
        if all(exists):
            return

        # Check if zip file already exists (if so then extract)
        filepath = os.path.join(self.root, filename)
        if os.path.exists(filepath):
            extract_archive(filepath)
            return

        # Check if the user requested to download the dataset
        if not self.download:
            raise DatasetNotFoundError(self)

        # Download and extract the dataset
        download_url(
            url, self.root, filename=filename, md5=md5 if self.checksum else None
        )
        filepath = os.path.join(self.root, filename)
        extract_archive(filepath)

    def plot(self, sample, show_titles=True, suptitle=None, hsi_indices=(0, 1, 2)):
        """Plot a sample from the dataset.

        Args:
            sample: a sample returned by :meth:`__getitem__`
            show_titles: flag indicating whether to show titles above each panel
            suptitle: optional string to use as a suptitle
            hsi_indices: tuple of indices to create HSI false color image

        Returns:
            a matplotlib Figure with the rendered sample
        """
        import matplotlib.pyplot as plt
        from matplotlib.patches import Rectangle

        assert len(hsi_indices) == 3

        ncols = 3

        hsi = ops.convert_to_numpy(ops.take(sample["hsi"], hsi_indices, axis=-1))
        hsi = quantile_normalization(hsi)

        chm = ops.convert_to_numpy(sample["chm"])
        chm = quantile_normalization(chm)
        if chm.ndim == 3 and chm.shape[-1] == 1:
            chm = chm[..., 0]

        image = ops.convert_to_numpy(sample["image"])

        boxes, labels = None, None
        if "bbox_xyxy" in sample and len(sample["bbox_xyxy"]):
            boxes = ops.convert_to_numpy(sample["bbox_xyxy"])
            if "label" in sample:
                labels = [
                    self.idx2class[int(i)]
                    for i in ops.convert_to_numpy(sample["label"])
                ]

        pred_boxes, pred_labels = None, None
        if "prediction_bbox_xyxy" in sample and len(sample["prediction_bbox_xyxy"]):
            ncols += 1
            pred_boxes = ops.convert_to_numpy(sample["prediction_bbox_xyxy"])
            if "prediction_label" in sample:
                pred_labels = [
                    self.idx2class[int(i)]
                    for i in ops.convert_to_numpy(sample["prediction_label"])
                ]

        fig, axs = plt.subplots(ncols=ncols, figsize=(ncols * 10, 10))
        axs[0].imshow(image)
        axs[0].axis("off")
        if boxes is not None:
            for i, box in enumerate(boxes):
                xmin, ymin, xmax, ymax = box
                axs[0].add_patch(
                    Rectangle(
                        (xmin, ymin),
                        xmax - xmin,
                        ymax - ymin,
                        fill=False,
                        edgecolor="red",
                    )
                )
                if labels is not None:
                    axs[0].text(xmin, ymin, labels[i], color="red", fontsize=8)

        axs[1].imshow(hsi)
        axs[1].axis("off")
        axs[2].imshow(chm)
        axs[2].axis("off")
        if ncols > 3:
            axs[3].imshow(image)
            axs[3].axis("off")
            if pred_boxes is not None:
                for i, box in enumerate(pred_boxes):
                    xmin, ymin, xmax, ymax = box
                    axs[3].add_patch(
                        Rectangle(
                            (xmin, ymin),
                            xmax - xmin,
                            ymax - ymin,
                            fill=False,
                            edgecolor="blue",
                        )
                    )
                    if pred_labels is not None:
                        axs[3].text(xmin, ymin, pred_labels[i], color="blue", fontsize=8)

        if show_titles:
            axs[0].set_title("Ground Truth")
            axs[1].set_title("Hyperspectral False Color Image")
            axs[2].set_title("Canopy Height Model")
            if ncols > 3:
                axs[3].set_title("Predictions")

        if suptitle is not None:
            plt.suptitle(suptitle)

        return fig
