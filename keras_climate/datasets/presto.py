"""Presto Embeddings dataset (ported from torchgeo.datasets.presto)."""

import numpy as np
import pandas as pd

from .geo import RasterDataset


class PrestoEmbeddings(RasterDataset):
    """Presto Embeddings dataset.

    `Geospatial embeddings <https://nasaharvest.github.io/presto-embeddings/>`__
    for Togo generated using the `Presto geospatial foundation model
    <https://arxiv.org/abs/2304.14065>`__.

    Presto geospatial embeddings provide a compressed representation of Earth
    Observation data, enabling more efficient mapping and analysis. Embeddings
    are generated by using the Presto encoder to compress location
    information, optical imagery (Sentinel-2), radar imagery (Sentinel-1),
    climatology data (ERA5), and elevation data (SRTM) over the course of a
    year (March 2019 - March 2020). Each embedding contains 128 features
    representing a single 10 m2 pixel on Earth.

    The dataset can be downloaded from one of two sources:

    * `Hugging Face <https://huggingface.co/datasets/izvonkov/Togo_Presto_Embeddings>`__
    * `Google Earth Engine <https://code.earthengine.google.com/?asset=users/izvonkov/Togo/Presto_embeddings_v2025_06_19>`__

    If you use this dataset in your research, please cite:

    * https://arxiv.org/abs/2511.02923
    """

    filename_glob = "Togo_Presto_embeddings_*"

    # Timestamp in filename is when embeddings were released, not the dates
    # they cover.
    mint = pd.Timestamp(2019, 3, 1)
    maxt = pd.Timestamp(2020, 3, 1)

    all_bands = tuple(map(str, range(128)))

    def plot(self, sample, show_titles=True, suptitle=None):
        """Plot a sample from the dataset.

        .. warning::
           Visualizations are generated using PCA on each image
           *individually*, and are thus not comparable across images. The
           plot method is provided for visualization purposes only and
           should not be used to draw conclusions.
        """
        import matplotlib.pyplot as plt
        from keras import ops

        image = ops.convert_to_numpy(sample["image"])
        h, w, c = image.shape
        A = image.reshape(h * w, c)

        # Use PCA to project embeddings from 128D to 3D space
        valid = A.sum(axis=1) != 0
        invalid = A.sum(axis=1) == 0

        A_centered = A[valid] - A[valid].mean(axis=0, keepdims=True)
        _, _, Vt = np.linalg.svd(A_centered, full_matrices=False)
        V = Vt[:3].T
        B = A @ V

        B -= B[valid].min(axis=0, keepdims=True)
        B /= B[valid].max(axis=0, keepdims=True)
        B[invalid] = 1
        image = B.reshape(h, w, 3)

        fig, ax = plt.subplots()
        ax.imshow(image)
        ax.axis("off")

        if show_titles:
            ax.set_title("Embedding")

        if suptitle is not None:
            plt.suptitle(suptitle)

        return fig
